describe('Mode base tests', () => {
	const struct = new Struct((ctx, order) => {
		ctx.order(order);

		// Moves to 0x04
		ctx.pad(3);
		ctx.align(4);

		ctx.u8('u8');
		ctx.u16('u16');
		ctx.u32('u32');
		ctx.u64('u64');

		ctx.i8('i8');
		ctx.i16('i16')
		ctx.i32('i32');
		ctx.i64('i64');

		ctx.f32('f32');
		ctx.f64('f64');

		ctx.u8(Literal(123));
		ctx.u16(Literal(1234));
		ctx.u32(Literal(12345));
		ctx.u64(Literal(123456n));

		ctx.i8(Literal(123));
		ctx.i16(Literal(1234))
		ctx.i32(Literal(12345));
		ctx.i64(Literal(123456n));

		ctx.f32(Literal(Math.fround(123.456)));
		ctx.f64(Literal(123.456));

		ctx.str('fixed', 5);
		ctx.str('nonfixed');
		ctx.str(Literal('fixed'), 5);
		ctx.str(Literal('nonfixed'));
	});

	it('Length mode', () => {
		let length!: number;
		assert.doesNotThrow(() => {length = struct.length(input, ['LE'])});
		assert.strictEqual(length, 116);
		assert.doesNotThrow(() => {length = struct.length(input, ['BE'])});
		assert.strictEqual(length, 116);
	});

	it('Pack mode', () => {
		const packed = new Uint8Array(116);
		assert.doesNotThrow(() => struct.pack(input, packed.buffer, ['LE']));
		assert.deepStrictEqual(packed, packed_LE);
		assert.doesNotThrow(() => struct.pack(input, packed.buffer, ['BE']));
		assert.deepStrictEqual(packed, packed_BE);
	});

	it('Unpack mode', () => {
		let unpacked = {};
		assert.doesNotThrow(() => struct.unpack(packed_LE.buffer, unpacked, ['LE']));
		assert.deepStrictEqual(unpacked, input);
		unpacked = {};
		assert.doesNotThrow(() => struct.unpack(packed_BE.buffer, unpacked, ['BE']));
		assert.deepStrictEqual(unpacked, input);
	});
});